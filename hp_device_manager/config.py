def get_default_system_dir() -> Path:
    """
    Returns standard system-wide directory:
    Windows: %ProgramData%\\HP\\HP DeskJet 2130 series
    Other: ~/.local/share/HP/HP DeskJet 2130 series
    """
    if platform.system() == "Windows":
        base = os.environ.get("ProgramData", r"C:\ProgramData")
    else:
        base = os.path.expanduser("~/.local/share")
    return Path(base) / VENDOR_NAME / PRODUCT_NAME
